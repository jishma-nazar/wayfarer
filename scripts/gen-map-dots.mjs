// Generates a dot-matrix land mask (equirectangular) from Natural Earth 110m.
// Run: node scripts/gen-map-dots.mjs  → writes src/lib/map-dots.ts
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";

const topo = JSON.parse(readFileSync("node_modules/world-atlas/land-110m.json", "utf8"));
const land = feature(topo, topo.objects.land);
// Rings that cross the antimeridian (Fiji, Chukotka, Antarctica) jump ±360° between vertices,
// which breaks point-in-polygon and paints whole rows of fake land. Unwrap them so they're continuous.
const unwrap = (ring) => {
  const out = [];
  let shift = 0;
  ring.forEach(([lon, lat], i) => {
    if (i > 0) {
      const prev = ring[i - 1][0];
      if (lon - prev > 180) shift -= 360;
      else if (prev - lon > 180) shift += 360;
    }
    out.push([lon + shift, lat]);
  });
  return out;
};
const polys = land.features
  .flatMap((f) => (f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates))
  .map((poly) => poly.map(unwrap));

function inRing(x, y, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
const inPoly = (lon, lat, p) => inRing(lon, lat, p[0]) && !p.slice(1).some((h) => inRing(lon, lat, h));
// Test the shifted copies too, since unwrapped rings can extend past ±180°.
const isLand = (lon, lat) => polys.some((p) => [0, 360, -360].some((d) => inPoly(lon + d, lat, p)));

const STEP = 2.6; // degrees between dots
const dots = [];
for (let lat = 72; lat >= -56; lat -= STEP) {
  for (let lon = -168; lon <= 180; lon += STEP) {
    if (isLand(lon, lat)) dots.push([+lon.toFixed(1), +lat.toFixed(1)]);
  }
}
// Must match project() in src/lib/geo.ts
const W = 1000, H = 368, LON0 = -168, LON1 = 180, LAT0 = 72, LAT1 = -56;
const px = (lon) => ((lon - LON0) / (LON1 - LON0)) * W;
const py = (lat) => ((LAT0 - lat) / (LAT0 - LAT1)) * H;
// One path of zero-length round-capped segments: tiny HTML, no per-dot nodes.
const d = dots.map(([lon, lat]) => `M${px(lon).toFixed(1)} ${py(lat).toFixed(1)}h0`).join("");
// Served as a static file and used as a CSS mask, so it stays themeable without weighing down the HTML.
writeFileSync(
  "public/map-dots.svg",
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}"><path d="${d}" stroke="#000" stroke-width="3.4" stroke-linecap="round"/></svg>\n`
);
writeFileSync(
  "src/lib/map-dots.ts",
  `// Generated by scripts/gen-map-dots.mjs — do not edit by hand.\n// Natural Earth 110m land, sampled every ${STEP}°, projected into a ${W}×${H} viewBox (dots: /public/map-dots.svg).\nexport const MAP_VIEWBOX = { width: ${W}, height: ${H} } as const;\n`
);
console.log(dots.length, "dots");
